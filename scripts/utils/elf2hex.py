#!/usr/bin/env python3
"""ELF -> $readmemh image: one 32-bit little-endian word per line, word 0 at --base.

    elf2hex.py build/sw/sum.elf -o build/sw/sum.hex --base 0x80000000

Reads the ELF program headers directly (no objcopy needed) and lays every PT_LOAD segment at its
physical address, so one $readmemh fills the testbench RAM exactly as the loader would. Gaps are
zero, and .bss, which has no file contents, stays zero as well.
"""

import argparse
import struct
import sys

PT_LOAD = 1


def load_segments(path):
    """Yield (paddr, bytes) for every PT_LOAD segment of a 32-bit little-endian ELF."""
    with open(path, "rb") as fd:
        elf = fd.read()

    if elf[:4] != b"\x7fELF":
        sys.exit(f"elf2hex.py: {path} is not an ELF file")
    if elf[4] != 1 or elf[5] != 1:
        sys.exit(f"elf2hex.py: {path} is not 32-bit little-endian (RV32)")

    e_phoff, = struct.unpack_from("<I", elf, 0x1c)
    e_phentsize, e_phnum = struct.unpack_from("<HH", elf, 0x2a)

    for i in range(e_phnum):
        p_type, p_offset, _p_vaddr, p_paddr, p_filesz, _p_memsz, _flags, _align = \
            struct.unpack_from("<8I", elf, e_phoff + i * e_phentsize)
        if p_type == PT_LOAD and p_filesz:
            yield p_paddr, elf[p_offset:p_offset + p_filesz]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("elf", help="input ELF")
    ap.add_argument("-o", "--output", required=True, help="output hex image")
    ap.add_argument("--base", default="0x80000000", help="address of word 0 (default 0x80000000)")
    args = ap.parse_args()

    base = int(args.base, 0)
    if base % 4:
        sys.exit(f"elf2hex.py: base {args.base} is not word aligned")

    segments = sorted(load_segments(args.elf))
    if not segments:
        sys.exit(f"elf2hex.py: {args.elf} has no loadable segment")

    image = bytearray()
    for paddr, data in segments:
        if paddr < base:
            sys.exit(f"elf2hex.py: segment at {paddr:#x} is below the base {base:#x}")
        start = paddr - base
        if start > len(image):
            image.extend(b"\0" * (start - len(image)))      # gap between segments
        image[start:start + len(data)] = data

    image.extend(b"\0" * (-len(image) % 4))
    words = [int.from_bytes(image[i:i + 4], "little") for i in range(0, len(image), 4)]

    with open(args.output, "w") as out:
        out.write(f"// Generated by elf2hex.py from {args.elf}, word 0 at {base:#x}\n")
        for i, word in enumerate(words):
            out.write(f"{word:08x}  // {base + 4 * i:08x}\n")

    print(f"elf2hex.py: {len(words)} words ({4 * len(words)} bytes) -> {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
