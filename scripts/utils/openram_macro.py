#!/usr/bin/env python3
"""Generate one OpenRAM SRAM macro, or characterize it with SPICE, one OpenRAM run per corner.

Usage: openram_macro.py --config <macro>.py --out DIR --run DIR [--publish DIR] [--char [--area-ref LIB]]

Called by `make openram` and `make openram-char` (syn/tech/openram45/openram45.mk), with the
tools of the project venv first on PATH. Each run starts from a configuration that executes the
original one and keeps a single corner, so OpenRAM characterizes one corner per process.

Without --char (make openram): the corners of use_specified_corners. The first run does the whole
flow of the configuration (layout, supply rings, DRC and LVS) and writes every view to --out; any
other corner lays out the same macro without DRC and LVS and contributes its Liberty file. The
script stops unless the log of the first run has a clean DRC and an LVS match (OpenRAM stops on an
LVS mismatch but only warns on DRC errors), and writes the Verilog model with VERBOSE = 0: the
model prints every access otherwise, and a netlist cannot override the parameter.

With --char (make openram-char): the corners of spice_corners, in parallel, with SPICE
characterization (analytical_delay = False) and without DRC and LVS, which make openram already
ran on the same layout. Only the Liberty files go to --out.

--publish copies the views the flows read to DIR, once every check has passed: the Liberty files,
plus the LEF and the Verilog model without --char. That is the copy kept in git
(syn/tech/openram45/views), so a clone simulates and synthesizes without running OpenRAM.

OpenRAM lays the macro out the same way every time, so the area of every Liberty file must agree,
with --area-ref too when it is given; the script checks it. Each run works in <run>/<corner>/:
openram.log, the derived configuration, tmp/ (OPENRAM_TMP, kept with -k: SPICE decks and results,
DRC and LVS reports) and, unless its views go to --out, views/. Exits 1 when a run fails or a check
does not pass.
"""
import argparse
import importlib.util
import os
import re
import runpy
import shutil
import subprocess
import sys
import time


def corner_name(corner):
    """The name OpenRAM gives a corner in its file names: ("SS", 0.95, 125) -> SS_0p95V_125C."""
    process, supply, temperature = corner
    return f"{process}_{supply}V_{temperature}C".replace(".", "p")


def log(macro, message):
    print(f"[openram] {macro}: {message}", flush=True)


def write_config(path, base_config, corner, overrides):
    with open(path, "w") as f:
        f.write(f"# Generated by scripts/utils/openram_macro.py: {os.path.basename(base_config)}"
                f" at {corner_name(corner)} only.\n")
        f.write(f"exec(open({base_config!r}).read())\n")
        f.write(f"use_specified_corners = [{corner!r}]\n")
        for name, value in overrides.items():
            f.write(f"{name} = {value!r}\n")


def lib_area(path):
    with open(path) as f:
        match = re.search(r"^\s*area\s*:\s*([0-9.eE+-]+)\s*;", f.read(), re.M)
    return float(match.group(1)) if match else None


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--config", required=True, help="OpenRAM configuration <macro>.py")
    parser.add_argument("--out", required=True, help="directory of the views")
    parser.add_argument("--run", required=True, help="directory of the runs, logs and temporaries")
    parser.add_argument("--char", action="store_true",
                        help="SPICE characterization at the corners of spice_corners")
    parser.add_argument("--area-ref", help="Liberty file whose area the new ones must match")
    parser.add_argument("--publish", help="directory that receives the views the flows read")
    args = parser.parse_args()

    base_config = os.path.abspath(args.config)
    macro = os.path.splitext(os.path.basename(base_config))[0]
    out_dir = os.path.abspath(args.out)
    run_dir = os.path.abspath(args.run)
    corner_list = "spice_corners" if args.char else "use_specified_corners"
    corners = runpy.run_path(base_config).get(corner_list)
    if not corners:
        sys.exit(f"[openram] {macro}: {base_config} lists no {corner_list}")
    compiler = os.path.join(os.path.dirname(importlib.util.find_spec("openram").origin),
                            "sram_compiler.py")
    os.makedirs(out_dir, exist_ok=True)

    runs = []
    for index, corner in enumerate(corners):
        name = corner_name(corner)
        work = os.path.join(run_dir, name)
        full_flow = index == 0 and not args.char
        views = out_dir if full_flow else os.path.join(work, "views")
        for d in (work, os.path.join(work, "tmp"), views):
            os.makedirs(d, exist_ok=True)
        overrides = {}
        if args.char:
            overrides["analytical_delay"] = False
        if not full_flow:
            overrides["check_lvsdrc"] = False
        config = os.path.join(work, f"{macro}.py")
        write_config(config, base_config, corner, overrides)
        log_path = os.path.join(work, "openram.log")
        env = dict(os.environ, OPENRAM_TMP=os.path.join(work, "tmp"))
        with open(log_path, "w") as log_file:
            proc = subprocess.Popen([sys.executable, compiler, "-v", "-k", "-o", macro, "-p", views,
                                     config], cwd=work, env=env, stdout=log_file,
                                    stderr=subprocess.STDOUT)
        runs.append(dict(name=name, proc=proc, log=log_path, views=views, start=time.time()))
        what = "layout, DRC and LVS, views" if full_flow else ("SPICE" if args.char else "Liberty only")
        log(macro, f"{name} started ({what}), OpenRAM log in {os.path.join(views, macro + '.log')}")

    failed = []
    pending = list(runs)
    while pending:
        time.sleep(10)
        for run in [r for r in pending if r["proc"].poll() is not None]:
            pending.remove(run)
            minutes = (time.time() - run["start"]) / 60
            if run["proc"].returncode:
                failed.append(run)
                log(macro, f"{run['name']} FAILED after {minutes:.0f} min, see {run['log']}")
            else:
                log(macro, f"{run['name']} done in {minutes:.0f} min")
    if failed:
        sys.exit(1)

    errors = []
    libs = [f"{macro}_{r['name']}.lib" for r in runs]
    for run in runs:
        if run["views"] != out_dir:
            shutil.copy2(os.path.join(run["views"], f"{macro}_{run['name']}.lib"), out_dir)
    views = libs if args.char else libs + [f"{macro}.{x}" for x in ("lef", "v", "gds")]
    for view in views:
        if not os.path.isfile(os.path.join(out_dir, view)):
            errors.append(f"OpenRAM wrote no {view}")

    if not args.char:
        first = runs[0]
        with open(first["log"], errors="replace") as f:
            text = f.read()
        if not re.search(rf"DRC Errors {macro}\s+0\s*$", text, re.M):
            errors.append(f"no clean DRC in {first['log']} (report in {os.path.dirname(first['log'])}/tmp)")
        if not re.search(rf"{macro}\s+LVS matches", text):
            errors.append(f"no LVS match in {first['log']} (report in {os.path.dirname(first['log'])}/tmp)")
        model = os.path.join(out_dir, f"{macro}.v")
        if os.path.isfile(model):
            with open(model) as f:
                text, count = re.subn(r"^(\s*parameter VERBOSE = )1\b", r"\g<1>0", f.read(), flags=re.M)
            if not count and not re.search(r"^\s*parameter VERBOSE = 0\b", text, re.M):
                errors.append(f"no VERBOSE parameter to turn off in {model}")
            with open(model, "w") as f:
                f.write(text)

    areas = {lib: lib_area(os.path.join(out_dir, lib)) for lib in libs
             if os.path.isfile(os.path.join(out_dir, lib))}
    if args.area_ref and os.path.isfile(args.area_ref):
        areas[os.path.basename(args.area_ref) + " (make openram)"] = lib_area(args.area_ref)
    if len(set(areas.values())) > 1:
        errors.append(f"the layouts of the runs differ, areas {areas}")
    for error in errors:
        log(macro, error)
    if errors:
        sys.exit(1)
    checks = "SPICE" if args.char else "DRC clean, LVS match"
    log(macro, f"done: {checks}, corners {', '.join(r['name'] for r in runs)},"
               f" area {next(iter(areas.values())):.0f} um2, in {out_dir}")
    if args.publish:
        publish = os.path.abspath(args.publish)
        os.makedirs(publish, exist_ok=True)
        files = libs if args.char else libs + [f"{macro}.lef", f"{macro}.v"]
        for name in files:
            shutil.copyfile(os.path.join(out_dir, name), os.path.join(publish, name))
        log(macro, f"published {', '.join(files)} to {publish} (commit them)")


if __name__ == "__main__":
    main()
