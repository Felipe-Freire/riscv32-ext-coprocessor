#!/usr/bin/env python3
"""Generate a random RV32I program for co-simulation, with Spike as the oracle.

    gen_random_test.py --seed 7 --count 2000 -o build/sw/random/random.S

A random program has no expected answer, and it does not need one: the testbench compares every
retired instruction against Spike, so the program only has to be deterministic and to terminate.
That removes the ceiling on hand-written tests, which is where corner cases hide.

What it emits, and why it stays inside the rules:
  * ALU, shift, compare, LUI and AUIPC on a pool of registers, any operands.
  * Shift amounts are masked to 0..31, so no shift is out of range.
  * Loads and stores go through a base register that is reloaded from the scratch area's address
    before each access, with an aligned offset inside it: never a fault, never misaligned.
  * Branches only jump forward, over the next few instructions, so the program cannot loop and
    always reaches the end.
  * x0 is never a destination that matters, sp/gp/tp and the registers crt0 needs are left alone.
  * No CSR, no ECALL, no FENCE.I, no WFI: those either differ from the reference by design or are
    covered by sw/tests/csr and sw/tests/trap.
"""

import argparse
import random
import sys

# Registers the program may use: t0-t6, a0-a7, s2-s11. sp, gp, tp, ra, s0 and s1 are left alone,
# s0 is the scratch base, s1 the loop-free marker.
POOL = ([5, 6, 7] + list(range(28, 32))        # t0-t2, t3-t6
        + list(range(10, 18))                  # a0-a7
        + list(range(18, 28)))                 # s2-s11

RR = ["add", "sub", "sll", "slt", "sltu", "xor", "srl", "sra", "or", "and"]
RI = ["addi", "slti", "sltiu", "xori", "ori", "andi"]
SHIFT_I = ["slli", "srli", "srai"]
BRANCH = ["beq", "bne", "blt", "bge", "bltu", "bgeu"]
LOAD = [("lw", 4), ("lh", 2), ("lhu", 2), ("lb", 1), ("lbu", 1)]
STORE = [("sw", 4), ("sh", 2), ("sb", 1)]

SCRATCH_WORDS = 32


def generate(rng, count):
    out, label = [], 0
    for _ in range(count):
        kind = rng.choices(
            ["rr", "ri", "shift", "upper", "load", "store", "branch"],
            weights=[32, 20, 10, 6, 12, 12, 8])[0]
        rd, rs1, rs2 = rng.choice(POOL), rng.choice(POOL), rng.choice(POOL)

        if kind == "rr":
            out.append(f"  {rng.choice(RR)} x{rd}, x{rs1}, x{rs2}")
        elif kind == "ri":
            out.append(f"  {rng.choice(RI)} x{rd}, x{rs1}, {rng.randint(-2048, 2047)}")
        elif kind == "shift":
            out.append(f"  {rng.choice(SHIFT_I)} x{rd}, x{rs1}, {rng.randint(0, 31)}")
        elif kind == "upper":
            imm = rng.randint(0, 0xFFFFF)
            out.append(f"  lui x{rd}, {imm}" if rng.random() < 0.7 else f"  auipc x{rd}, {imm}")
        elif kind in ("load", "store"):
            # The base is reloaded every time, so no earlier instruction can push it out of range.
            name, width = rng.choice(LOAD if kind == "load" else STORE)
            offset = rng.randrange(0, (SCRATCH_WORDS - 1) * 4, width)
            out.append(f"  la x{rs1}, random_scratch")
            if kind == "load":
                out.append(f"  {name} x{rd}, {offset}(x{rs1})")
            else:
                out.append(f"  {name} x{rs2}, {offset}(x{rs1})")
        else:
            # Forward only: the program is a straight line and always terminates.
            label += 1
            skip = rng.randint(1, 3)
            out.append(f"  {rng.choice(BRANCH)} x{rs1}, x{rs2}, rnd_{label}")
            for _ in range(skip):
                out.append(f"  addi x{rng.choice(POOL)}, x{rng.choice(POOL)}, "
                           f"{rng.randint(-16, 16)}")
            out.append(f"rnd_{label}:")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--output", required=True, help="assembly file to write")
    ap.add_argument("--seed", type=int, default=1, help="random seed (default 1)")
    ap.add_argument("--count", type=int, default=1000,
                    help="instructions to generate (default 1000)")
    args = ap.parse_args()

    if args.count < 1:
        sys.exit("gen_random_test.py: --count must be at least 1")

    rng = random.Random(args.seed)
    body = generate(rng, args.count)

    with open(args.output, "w") as fd:
        fd.write(f"""// Generated by gen_random_test.py --seed {args.seed} --count {args.count}
// Do not edit: regenerate it instead.
//
// A random straight-line RV32I program. There is nothing to self-check, so main always returns 0:
// the check is the retirement trace, which must match Spike instruction for instruction. Memory
// accesses all go to random_scratch through a base register reloaded right before each one, and
// every branch jumps forward, so the program faults nowhere and always terminates.

  .section .text
  .globl main
main:
  addi sp, sp, -16
  sw   ra, 12(sp)

  // Start from a known state, or the first instructions would read whatever crt0 left behind.
""")
        for reg in POOL:
            fd.write(f"  li   x{reg}, {reg}\n")
        fd.write("\n")
        fd.write("\n".join(body))
        fd.write(f"""

  li   a0, 0
  lw   ra, 12(sp)
  addi sp, sp, 16
  ret

  .section .data
  .align 2
random_scratch:
  .fill {SCRATCH_WORDS}, 4, 0x5A5A5A5A
""")
    print(f"gen_random_test.py: seed {args.seed}, {args.count} instructions -> {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
